#!/usr/bin/env python3
"""ngspice references of the measurement circuits (PLAN.md step 2).

For each circuit: out/spice/<id>.cir from the KiCad netlist (spice/extract.py), `ngspice -b`,
then out/spice/<id>_spice.csv (test_plot.py format: #FREQRESPONSE frequency,magnitude_db,
phase_deg) and out/spice/<id>_op.json (operating point, DC gain from a two-point .dc).

    python3 simulation/spice/run_ac.py              # all circuits, one ngspice at a time
    python3 simulation/spice/run_ac.py c1 c5        # some
    python3 simulation/spice/run_ac.py --no-run     # netlists only

ngspice: --ngspice PATH, $NGSPICE, or PATH (same lookup as hVHDL_ode fc_5level.py).

Netlist rules:
  * all R / C of the circuit with the schematic values; not-fitted parts (value 'na') left out
  * circuits 1-5 share +2V5_BIAS: their netlists hold all five circuits and the bias network
    (REF1 = ideal source on its VOUT net, value set for 1.65 V on the loaded bias node);
    only the circuit under test is driven, the other inputs sit at their DC value
  * op-amps: the macromodel of circuits.OPAMPS (spice/models/opamp_macro.lib), no rails
  * group B: C_PAR_PER_MOHM across every 1 Mohm resistor of the chains
  * ADC inputs (AD1/AD2) and the J2 lines are not loaded
  * the isolated grounds (ISO_GND, HT_GND) are node 0 of their own circuit
"""
import argparse
import json
import math
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
sys.path.insert(0, str(SIM))
sys.path.insert(0, str(HERE))
import circuits as C  # noqa: E402
import extract as X  # noqa: E402

OUTDIR = SIM / "out/spice"
MODEL_LIB = HERE / "models/opamp_macro.lib"


def find_ngspice(explicit=None):
    for cand in (explicit, os.environ.get("NGSPICE"), shutil.which("ngspice")):
        if cand and Path(cand).exists():
            return cand
    raise SystemExit("ngspice not found: put it on PATH, set NGSPICE=..., or pass --ngspice")


def model_lib():
    """The op-amp macromodel subcircuits (one per part, parameters from circuits.OPAMPS)."""
    lines = ["* op-amp macromodels, generated from simulation/circuits.py OPAMPS",
             "* gm stage into R1 || C1: A0 at DC, one pole at GBW / A0; unity buffer; Rout",
             "* the VHDL model (vhdl/meas_models_pkg.vhd) uses the same equations"]
    for part, m in C.OPAMPS.items():
        lines += [f".subckt opamp_{part} inp inn out",
                  f"G1 0 x inp inn {m['a0'] / 1e3:.10g}",
                  "R1 x 0 1k",
                  f"C1 x 0 {m['a0'] / (2 * math.pi * m['gbw'] * 1e3):.10g}",
                  "E1 o 0 x 0 1",
                  f"Ro o out {m['rout']:.10g}",
                  ".ends", ""]
    return "\n".join(lines)


class Nodes:
    def __init__(self, ground):
        self.ground, self.map = set(ground), {}

    def __call__(self, net):
        if net in self.ground:
            return "0"
        if net not in self.map:
            s = re.sub(r"[^A-Za-z0-9_]", "_", net).strip("_") or "n"
            name, i = f"n_{s}", 1
            while name in self.map.values():
                name, i = f"n_{s}_{i}", i + 1
            self.map[net] = name
        return self.map[net]


def netlist(nl, c, dc_step=None):
    """The .cir text of circuit c (driven input = c's), plus node names used."""
    group = C.bias_circuits() if c["ref"] == "bias" else [c]
    nodes = Nodes(C.GROUNDS)
    refs = []
    for cc in group:
        refs += [r for r in C.circuit_refs(cc) if r not in refs]
    bias = X.bias_network(nl) if c["ref"] == "bias" else None
    if bias:
        b = C.BIAS_REFS
        refs += [b["r_top"], b["r_bot"], b["c_bias"], b["c_ref"]]
    chain_1m = set()
    for cc in group:
        if cc["group"] == "B":
            chain_1m |= {r for r in cc["roles"]["in_p"] + cc["roles"]["g"] if nl.val(r) >= 1e6}

    out = [f"* {c['id']}: {c['title']}  (generated by simulation/spice/run_ac.py from the KiCad netlist)"]
    for r in refs:
        part = nl.value[r]
        if r[0] in "RC":
            v = nl.val(r)
            a, bnet = nl.two_pin(r)
            if v is None:
                out.append(f"* {r} {part} not fitted ({a}, {bnet})")
                continue
            out.append(f"{r} {nodes(a)} {nodes(bnet)} {v:.10g}")
            if r in chain_1m:
                out.append(f"CPAR_{r} {nodes(a)} {nodes(bnet)} {C.C_PAR_PER_MOHM * v / 1e6:.10g}")
        elif part in C.OPAMPS:
            pins = nl.pins[r]
            for unit, (p, m, o) in C.OPAMPS[part]["pins"].items():
                out.append(f"X{r}{unit} {nodes(pins[p])} {nodes(pins[m])} {nodes(pins[o])} opamp_{part}")
        elif r.startswith("AD"):
            out.append(f"* {r} ({part}) input not loaded")
        else:
            raise SystemExit(f"{c['id']}: no SPICE rule for {r} {part}")
    if bias:
        ref_out = nl.pins[C.BIAS_REFS["ref"]]["3"]
        out.append(f"* REF1 {nl.value[C.BIAS_REFS['ref']]}: ideal source, {bias['vref']:.6f} V "
                   f"-> {C.BIAS_VOLTAGE} V on the loaded {C.BIAS_NET}")
        out.append(f"VREF1 {nodes(ref_out)} 0 DC {bias['vref']:.10g}")
    for cc in group:
        inp = cc["input"]
        ac = " AC 1" if cc is c else ""
        if inp["kind"] == "I":
            # current into the shunt's pin 1 (positive = positive shunt voltage)
            out.append(f"I_{cc['id']} 0 {nodes(inp['net'])} DC {inp['dc']:.10g}{ac}")
        else:
            out.append(f"V_{cc['id']} {nodes(inp['net'])} 0 DC {inp['dc']:.10g}{ac}")
        for net, v in inp.get("hold", {}).items():
            out.append(f"V_{cc['id']}_{re.sub(r'[^A-Za-z0-9]', '', net)} {nodes(net)} 0 DC {v:.10g}")
    src = ("I_" if c["input"]["kind"] == "I" else "V_") + c["id"]
    v0 = c["input"]["dc"]
    dv = dc_step or (1.0 if c["input"]["kind"] == "I" else max(1.0, abs(v0) * 0.1))
    o, bn = nodes(c["out"]), nodes(C.BIAS_NET) if bias else None
    probes = f"v({o})" + (f" v({bn})" if bn else "")
    out += ["", f".include {MODEL_LIB.name}", "",
            ".control", "set wr_singlescale", "set wr_vecnames", "set noaskquit",
            "op", f"wrdata {c['id']}_op.txt {probes}",
            f"dc {src} {v0:.10g} {v0 + dv:.10g} {dv:.10g}", f"wrdata {c['id']}_dc.txt v({o})",
            f"ac dec {C.AC_PER_DECADE} {C.AC_START:g} {C.AC_STOP:g}",
            f"wrdata {c['id']}_ac.txt v({o})", ".endc", ".end", ""]
    return "\n".join(out), dict(out=o, bias=bn, dv=dv)


def read_wrdata(path):
    rows = [l.split() for l in Path(path).read_text().splitlines()[1:] if l.strip()]
    return [[float(x) for x in r] for r in rows]


def run(nl, c, ngspice, do_run=True):
    OUTDIR.mkdir(parents=True, exist_ok=True)
    (OUTDIR / MODEL_LIB.name).write_text(model_lib())
    text, info = netlist(nl, c)
    cir = OUTDIR / f"{c['id']}.cir"
    cir.write_text(text)
    if not do_run:
        return None
    r = subprocess.run([ngspice, "-b", cir.name], cwd=OUTDIR, capture_output=True, text=True,
                       timeout=600)
    (OUTDIR / f"{c['id']}.log").write_text(r.stdout + r.stderr)
    if r.returncode != 0 or not (OUTDIR / f"{c['id']}_ac.txt").exists():
        raise SystemExit(f"ngspice failed on {cir}, see {c['id']}.log")
    op = read_wrdata(OUTDIR / f"{c['id']}_op.txt")[0]
    dc = read_wrdata(OUTDIR / f"{c['id']}_dc.txt")
    ac = read_wrdata(OUTDIR / f"{c['id']}_ac.txt")
    f = [row[0] for row in ac]
    h = [complex(row[1], row[2]) for row in ac]
    mag = [20 * math.log10(abs(x)) for x in h]
    ph, prev = [], 0.0
    for x in h:                                  # unwrapped phase
        p = math.degrees(math.atan2(x.imag, x.real))
        p += 360.0 * round((prev - p) / 360.0)
        ph.append(p)
        prev = p
    with open(OUTDIR / f"{c['id']}_spice.csv", "w") as fo:
        fo.write("#FREQRESPONSE\n")
        fo.write(f"#CONFIG label={c['id']} ngspice .ac\n")
        fo.write("frequency,magnitude_db,phase_deg\n")
        for row in zip(f, mag, ph):
            fo.write("{:.10g},{:.10g},{:.10g}\n".format(*row))
    res = dict(id=c["id"], out_op=op[1], bias_op=op[2] if len(op) > 2 else None,
               dc_gain=(dc[1][1] - dc[0][1]) / info["dv"], input_dc=c["input"]["dc"],
               expected_dc_gain=X.expected_dc_gain(nl, c))
    (OUTDIR / f"{c['id']}_op.json").write_text(json.dumps(res, indent=1))
    return res


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("ids", nargs="*")
    ap.add_argument("--ngspice")
    ap.add_argument("--no-run", action="store_true")
    a = ap.parse_args(argv)
    nl = X.Netlist()
    ngspice = None if a.no_run else find_ngspice(a.ngspice)
    for cid in a.ids or [c["id"] for c in C.CIRCUITS]:
        res = run(nl, C.BY_ID[cid], ngspice, not a.no_run)
        if res:
            bias = f", bias {res['bias_op']:.4f} V" if res["bias_op"] is not None else ""
            print(f"{cid}: out {res['out_op']:.4f} V at input {res['input_dc']:g}{bias}, DC gain "
                  f"{res['dc_gain']:.6g} (ideal {res['expected_dc_gain']:.6g}, "
                  f"{100 * (res['dc_gain'] / res['expected_dc_gain'] - 1):+.3f} %)")
        else:
            print(f"{cid}: {OUTDIR / (cid + '.cir')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
