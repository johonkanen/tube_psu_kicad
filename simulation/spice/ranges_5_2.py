#!/usr/bin/env python3
"""5.2 channel ranges: gains, offsets and the J2 output range of every ADC channel.

From the 5.2 ngspice references (out/5.2/spice/<id>_op.json: DC gain and operating point, and
<id>_spice.csv), run `python3 simulation/run_sim.py --rev 5.2` (or run_ac.py --rev 5.2) first.
Output range of the J2 pin: 0.04 .. 3.26 V (LMH6643: 40 mV from the rails at 2 k; TLV316 /
TLV9062 rail-to-rail, same margin taken), ADC 0 .. 3.3 V, 14 bit (201 uV).
LMH6643 Vos (SNOS966Q, 3 V table): 3.4 mV max at 25 C, 7 mV max over temperature; the task
value 5 mV is shown as well. Input-referred current = Vos * noise gain / channel gain.

    python3 simulation/spice/ranges_5_2.py      # -> out/5.2/ranges_results.md
"""
import json
import math
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
os.environ["MEAS_SIM_REV"] = "5.2"
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import circuits as C  # noqa: E402
import extract as X  # noqa: E402

VLO, VHI, LSB = 0.04, 3.26, 3.3 / 2 ** 14


def op(cid):
    return json.loads((C.SPICE_OUT / f"{cid}_op.json").read_text())


def mag_db(cid, f):
    rows = [l.split(",") for l in (C.SPICE_OUT / f"{cid}_spice.csv").read_text().splitlines()[3:]]
    r = min(rows, key=lambda x: abs(math.log(float(x[0]) / f)))
    return float(r[1])


def main():
    nl = X.Netlist()
    b = X.bias_network(nl)
    L = ["# 5.2 channel ranges (generated by simulation/spice/ranges_5_2.py)", "",
         f"Bias: REF3325 2.5 V -> divider {b['vdiv']:.4f} V -> U9 -> R131 22R: bias node "
         f"{b['v_bias']:.4f} V ({1e3 * (b['vdiv'] - b['v_bias']):.1f} mV drop at {1e3 * b['i_loads']:.3f} mA "
         "of + leg loads). Tolerance (not simulated): REF3325 0.15 %, R110/R3 1 % -> ratio "
         "+-0.68 % -> about +-14 mV, plus the TLV316 offset; common to all bias-referenced channels "
         "(zero calibration). Output range 0.04 .. 3.26 V.", "",
         "## Current channels (LMH6643)", "",
         "| channel | gain (ngspice) | output at 0 A | range -/+ | noise gain | Vos 3.4 / 5 / 7 mV -> | "
         "range after 7 mV Vos | 1 LSB |",
         "|---|---|---|---|---|---|---|---|"]
    for c in C.CIRCUITS:
        if c["group"] != "A":
            continue
        o = op(c["id"])
        p = X.circuit_params(nl, c)
        g, v0 = o["dc_gain"], o["out_op"]
        ng = 1 + p["f"] / sum(p["g"])
        ineg, ipos = (v0 - VLO) / g, (VHI - v0) / g
        ios = [v * ng / g for v in (3.4e-3, 5e-3, 7e-3)]
        L.append(f"| {c['title']} | {g * 1e3:.2f} mV/A | {v0:.4f} V | -{ineg:.2f} / +{ipos:.2f} A | {ng:.1f} | "
                 + " / ".join(f"{x:.2f}" for x in ios) + " A | "
                 f"-{ineg - ios[2]:.2f} / +{ipos - ios[2]:.2f} A | {LSB / g * 1e3:.2f} mA |")
    L += ["", "LMH6643 input common mode: + inputs at bias x Rref / (Rin + Rref) = 1.57 / 1.61 / 1.63 V "
          "(PFC / DHB / HEATER), inside the CMVR (V+ - 1.2 V min = 2.1 V at 3.3 V, 1.9 V over temperature).",
          "", "## Voltage channels", "",
          "| channel | gain (ngspice) | ideal | output at | full scale (3.26 V) | 1 LSB | -3 dB | |H| 1 / 10 / 50 MHz rel. DC |",
          "|---|---|---|---|---|---|---|---|"]
    rows = dict(c5=("264 V rms (373 V pk)", 264 * math.sqrt(2)), c6=("400 V", 400.0), c7=("15 V", 15.0),
                c10=("5.0 V", 5.0), c8=("420 V", 420.0), c9=("6.3 V", 6.3))
    for cid, (txt, vin) in rows.items():
        c = C.BY_ID[cid]
        o = op(cid)
        g = o["dc_gain"]
        dc_db = 20 * math.log10(g)
        hf = " / ".join(f"{mag_db(cid, f) - dc_db:+.0f}" for f in (1e6, 10e6, 50e6))
        f3 = None
        rows_csv = [l.split(",") for l in (C.SPICE_OUT / f"{cid}_spice.csv").read_text().splitlines()[3:]]
        for fr, m, _ in rows_csv:
            if float(m) < dc_db - 3.0103:
                f3 = float(fr)
                break
        f3s = ("none" if not f3 else f"{f3 / 1e6:.3g} MHz" if f3 >= 1e6 else
               f"{f3 / 1e3:.3g} kHz" if f3 >= 1e3 else f"{f3:.3g} Hz")
        lsb = (f"{LSB / g * 1e3:.3g} mV" if cid not in ("c8", "c9")
               else f"{3.3 / 4096 / g * 1e3:.3g} mV (12 bit)")
        if cid == "c5":
            v0 = o["out_op"]
            outs = f"{v0 - g * vin:.3f} .. {v0 + g * vin:.3f} V at {txt}"
            fs = f"+-{min(v0 - VLO, VHI - v0) / g:.0f} V pk ({min(v0 - VLO, VHI - v0) / g / math.sqrt(2):.0f} V rms)"
        else:
            outs = f"{g * vin:.3f} V at {txt}"
            fs = f"{VHI / g:.4g} V" if cid not in ("c8", "c9") else f"{3.3 / g:.4g} V (ADC VA)"
        L.append(f"| {c['title']} | {g:.6g} | {o['expected_dc_gain']:.6g} | {outs} | {fs} | "
                 f"{lsb} | {f3s} | {hf} dB |")
    L += ["", "VAC gain is +0.18 % above the ideal 0.004: the line injects into the bias through the "
          "22R (7.3e-6 V/V, bias_buffer_results.md); 5.1 had +0.94 %. 5V_MEAS: R133 / R134 0.1 % -> "
          "gain +-0.08 %; TLV9062 offset adds a few mV / 0.4 on the 5 V reading.", ""]
    (C.OUT / "ranges_results.md").write_text("\n".join(L))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
