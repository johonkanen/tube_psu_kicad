#!/usr/bin/env python3
"""Writes simulation/vhdl/meas_params_pkg.vhd: the VHDL parameter sets of the 9 circuits
and the frequency bands, from the KiCad schematic (spice/extract.py) and circuits.py.

    python3 simulation/gen_params.py           # (re)write
    python3 simulation/gen_params.py --check   # exit 1 if the file is not up to date

run_sim.py regenerates it before every run.
"""
import sys
from pathlib import Path

SIM = Path(__file__).resolve().parent
sys.path.insert(0, str(SIM))
sys.path.insert(0, str(SIM / "spice"))
import circuits as C  # noqa: E402
import extract as X  # noqa: E402

TARGET = SIM / "vhdl/meas_params_pkg.vhd"
DITHER_OUT = 0.1        # dither amplitude, referred to the output [V]


def r(x):
    return f"{x:.10e}"


def r3(vals):
    vals = list(vals) + [0.0] * (3 - len(vals))
    return "(" + ", ".join(r(v) for v in vals) + ")"


def params(nl, c):
    p = X.circuit_params(nl, c)
    bias = X.bias_network(nl)
    has_bias = c["ref"] == "bias"
    others = [v for k, v in bias["loads"].items() if k != c["id"]]
    oa = p.get("opamp") or dict(a0=1.0, gbw=1.0, rout=0.0)
    g = X.expected_dc_gain(nl, c)
    f = dict(
        has_opamp="true" if c["opamp"] else "false",
        has_bias="true" if has_bias else "false",
        in_scale=r(p["shunt"] if c["group"] == "A" else 1.0),
        n_in_p=str(len(p["in_p"])), r_in_p=r3(p["in_p"]),
        r_ref_p=r(p["ref_p"]), c_ref_p=r(p["c_ref_p"] or 0.0), c_par=r(p["c_par"]),
        n_g=str(len(p.get("g", [1.0]))), r_g=r3(p.get("g", [1.0])),
        r_f=r(p.get("f") or 1.0), c_f=r(p.get("c_f") or 0.0),
        r_o=r(p.get("o") or 1.0), c_o=r(p.get("c_o") or 0.0),
        a0=r(oa["a0"]), gbw=r(oa["gbw"]), rout=r(oa["rout"]),
        vref=r(bias["vref"] if has_bias else 0.0),
        r_btop=r(bias["r_top"]), r_bbot=r(bias["r_bot"]), c_bias=r(bias["c_bias"]),
        r_bother=r(1.0 / sum(1.0 / x for x in others) if has_bias else 1.0),
        u0=r(c["input"]["dc"]), u_amp=r(DITHER_OUT / abs(g)))
    body = ",\n".join(f"            {k:9} => {v}" for k, v in f.items())
    return f"        -- {c['id']}: {c['title']} (group {c['group']})\n        {nl_ids(c)} => (\n{body})"


def nl_ids(c):
    return str(C.CIRCUITS.index(c) + 1)


def text(nl):
    sets = ",\n".join(params(nl, c) for c in C.CIRCUITS)
    bands = ",\n".join(f"        {i} => (fs => {r(b['fs'])}, nperseg => {b['nperseg']}, "
                       f"windows => {b['windows']}, f_lo => {r(b['f_lo'])}, f_hi => {r(b['f_hi'])})"
                       for i, b in enumerate(C.BANDS))
    return f"""-- GENERATED by simulation/gen_params.py from the KiCad schematic and simulation/circuits.py.
-- Do not edit. Index = circuit number (c1..c{len(C.CIRCUITS)}).
library work;
    use work.meas_models_pkg.all;

package meas_params_pkg is

    type meas_params_array is array (natural range <>) of meas_params_t;
    type band_array is array (natural range <>) of band_t;

    constant MEAS_PARAMS : meas_params_array(1 to {len(C.CIRCUITS)}) := (
{sets});

    constant BANDS : band_array(0 to {len(C.BANDS) - 1}) := (
{bands});

end package meas_params_pkg;
"""


def main(argv):
    new = text(X.Netlist())
    if "--check" in argv:
        ok = TARGET.exists() and TARGET.read_text() == new
        print(f"{TARGET.name}: {'up to date' if ok else 'OUT OF DATE (run simulation/gen_params.py)'}")
        return 0 if ok else 1
    TARGET.write_text(new)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
