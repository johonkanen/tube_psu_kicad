#!/usr/bin/env python3
"""Tables for the ICE5AR4780BZS controller study (EEL19_DESIGN.md section 13): every case of the
ICE5AR options next to the iW1819-model results of the same windings. Reads the cached
run_flyback.py / ice5ar_checks.py / losses.py results and writes ice5ar_results.md.

    python3 simulation/flyback/ice5ar_report.py
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import flyback_sim as fs  # noqa: E402
import ice5ar_sim as ice  # noqa: E402
import options as opts  # noqa: E402
import run_flyback as rf  # noqa: E402

OUT = os.path.join(HERE, "out")
RAILS = list(fs.RAILS)
DN = {"20V": "15V", "5V": "5V", "20V_ISO_SEC": "15V_ISO_SEC", "5V_ISOL": "5V_ISOL", "-5V_SEC": "−5V", "-100V BIAS": "−80V"}
STD = [c["name"] for c in rf.cases()]
FULL = [c["name"] for c in rf.FULL_CASES]
ALL = STD + FULL
PAIRS = [("eel19_tiw_sandwich_s_pre3_ice", "eel19_tiw_sandwich_s_pre3"),
         ("eel19_sandwich_b_pre3_ice", "eel19_sandwich_b_pre3")]
RTH = {"min Cu (datasheet)": 107.0, "≈ 2 cm² Cu on the drain pins (assumed)": 80.0}
TA = 50.0          # ambient of the datasheet power rating
P_CTRL = 14.4 * 1.5e-3   # controller: VCC x (IVCC_Normal 0.9 mA + gate drive ~0.6 mA)


def load(name):
    res = {}
    for c in rf.all_cases():
        p = os.path.join(OUT, "results", f"{name}__{c['name']}.json")
        if os.path.exists(p):
            res[c["name"]] = json.load(open(p))
    return res


def rng(res, rail, cases):
    v = [res[c][rail] for c in cases if c in res and res[c].get(rail) is not None]
    return (min(v), max(v)) if v else (None, None)


def f2(x, d=2):
    return "–" if x is None else f"{x:.{d}f}"


def losses(name, case):
    p = os.path.join(OUT, "losses", f"{name}.json" if case == "nom" else f"{name}__{case}.json")
    return json.load(open(p)) if os.path.exists(p) else {}


def main():
    s = ["# ICE5AR4780BZS controller – result tables", "",
         "Generated by `python3 simulation/flyback/ice5ar_report.py` from the cached results of "
         "`run_flyback.py` (ICE5AR options, `ice5ar_sim.py`) and of the iW1819-model options with the "
         "same windings. Voltages are magnitudes; 15V = net `20V` in the scripts. Standard range = the "
         "16 standard cases (15 at 400 V + nom325); full10 / full15 / full15_325 separately.", ""]
    # summary min-max
    s += ["## Rails: nominal (min–max) over the 16 standard cases, and the full-load cases", "",
          "| option | controller | " + " | ".join(DN[r] for r in RAILS) + " | VDS / Vcol max (std / full15) |",
          "|---|---|" + "---|" * len(RAILS) + "---|"]
    for a, b in PAIRS:
        for name, ctl in ((a, "ICE5AR"), (b, "iW1819")):
            res = load(name)
            if "nom" not in res:
                continue
            cells = []
            for r in RAILS:
                lo, hi = rng(res, r, STD)
                cells.append(f"{res['nom'][r]:.2f} ({lo:.2f}–{hi:.2f})" if r != "-100V BIAS" else f"{res['nom'][r]:.1f} ({lo:.1f}–{hi:.1f})")
            vstd = max(res[c]["vcol"] for c in STD if c in res)
            vf = res.get("full15", {}).get("vcol")
            s.append(f"| {b} | {ctl} | " + " | ".join(cells) + f" | {vstd:.0f} / {f2(vf, 0)} |")
    s.append("")
    # per case tables
    for a, b in PAIRS:
        res, ref = load(a), load(b)
        if not res:
            continue
        s += [f"## {a} – every case (iW1819 model in brackets)", "",
              "| case | " + " | ".join(DN[r] for r in RAILS) + " | FB V | f kHz | Pin W | Ipk A | VDS pk V | VCC V | drift 15V mV |",
              "|---|" + "---|" * (len(RAILS) + 7)]
        for c in ALL:
            if c not in res:
                continue
            r, q = res[c], ref.get(c, {})
            cells = []
            for k in RAILS:
                d = 1 if k == "-100V BIAS" else 2
                cells.append(f"{r[k]:.{d}f} ({f2(q.get(k), d)})")
            vcc = f"{r['vcc_min']:.1f}–{r['vcc_max']:.1f}" + (f" **{r['vcc_flag']}**" if r.get("vcc_flag") else "")
            s.append(f"| {c} | " + " | ".join(cells) +
                     f" | {r['fb']:.2f} | {r['fsw'] / 1e3:.0f} | {r['pin']:.2f} ({f2(q.get('pin'))}) | {r['ipri']:.2f} | "
                     f"{r['vcol']:.0f} ({f2(q.get('vcol'), 0)}) | {vcc} | {r['20V drift'] * 1e3:+.0f} |")
        s.append("")
        # ripple in the averaging window (scaled capacitors: an upper bound)
        s += [f"Peak-to-peak in the averaging window, mV (scaled capacitors, so larger than on the board; the "
              f"real-capacitor ripple is in the checks below):", "",
              "| case | " + " | ".join(DN[r] for r in RAILS) + " |", "|---|" + "---|" * len(RAILS)]
        for c in ALL:
            if c in res and res[c].get("5V max") is not None:
                s.append(f"| {c} | " + " | ".join(f"{(res[c][k + ' max'] - res[c][k + ' min']) * 1e3:.0f}" for k in RAILS) + " |")
        s.append("")
        # losses
        s += [f"Losses of {a} (switch: RDS(on) 8.7 Ω hot, incl. capacitive turn-on and the turn-off overlap of the "
              "model's 10 ns gate RC, which is pessimistic: with a 2 ns gate RC the full15 switch loss is 0.27 W instead of 0.75 W; "
              "Tj from the 10 ns figure is an upper bound; "
              "clamp = R72 + R45; windings / core from losses.py, MKF upper bound as in section 12):", "",
              "| case | Pin W | switch W | Rcs W | clamp W | winding W | core W | Tj (" + " / ".join(RTH) + f"), Ta {TA:.0f} °C |",
              "|---|---|---|---|---|---|---|---|"]
        for c in ("light", "idle", "nom", "nom325", "full10", "full15", "full15_325"):
            if c not in res:
                continue
            r = res[c]
            lo = losses(a, c)
            pic = r["psw"] + P_CTRL
            tj = " / ".join(f"{TA + rth * pic:.0f}" for rth in RTH.values())
            s.append(f"| {c} | {r['pin']:.2f} | {r['psw']:.3f} | {r['prcs']:.3f} | {r['pr72'] + r['pr45']:.3f} | "
                     f"{f2(lo.get('winding_losses_W'))} | {f2(lo.get('core_losses_W_IGSE'), 3)} | {tj} |")
        s.append("")
    # ABM variants
    var = [n for n in opts.EEL19_ICE_OPTIONS if "abm" in n or n.endswith(("_prehalf", "_prenone"))]
    rows = []
    for n in var:
        res = load(n)
        for c in ALL:
            if c in res:
                r = res[c]
                rows.append(f"| {n} | {c} | " + " | ".join(f"{r[k]:.2f}" for k in RAILS) +
                            f" | {r['abm']:.2f} | {r['fb']:.2f} | {r['pin']:.2f} | " +
                            " | ".join(f"{(r[k + ' max'] - r[k + ' min']) * 1e3:.0f}" for k in ("20V", "5V", "20V_ISO_SEC")) + " |")
    if rows:
        s += ["## Active Burst Mode and preload variants (TIW build, light-load cases)", "",
              "| option | case | " + " | ".join(DN[r] for r in RAILS) + " | ABM fraction | FB V | Pin W | pp 15V mV | pp 5V mV | pp 15V_ISO mV |",
              "|---|---|" + "---|" * (len(RAILS) + 6)]
        s += rows + [""]
    # checks
    chk = sorted(f for f in os.listdir(os.path.join(OUT, "checks")) if f.startswith("ice_") and f.endswith(".json")) \
        if os.path.isdir(os.path.join(OUT, "checks")) else []
    if chk:
        s += ["## Checks with the real capacitors and the real FB network (`ice5ar_checks.py`)", ""]
        for f in chk:
            r = json.load(open(os.path.join(OUT, "checks", f)))
            s.append(f"- **{f[:-5]}** ({r['config']}; comp {r['case'].get('comp')}): " +
                     ", ".join(f"{DN[k]} {r[k]:.3f} [{r[k + ' min']:.3f}–{r[k + ' max']:.3f}]" for k in RAILS) +
                     f"; FB {r['fb']:.2f} V, ABM {r['abm']:.2f}, Pin {r['pin']:.2f} W")
            for k, v in r.items():
                if k.startswith("w_"):
                    s.append(f"  - {k[2:]}: {v}")
        s.append("")
    with open(os.path.join(HERE, "ice5ar_results.md"), "w") as f:
        f.write("\n".join(s) + "\n")
    print("wrote ice5ar_results.md")


if __name__ == "__main__":
    main()
