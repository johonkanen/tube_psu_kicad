#!/usr/bin/env python3
"""Tables and geometry plots for the EEL19 options (EEL19_DESIGN.md), next to the EF20
recommendation margin_sandwich_8_pre. Reads the cached results of run_flyback.py and writes
eel19_results.md and geometry_eel19_*.png; does not touch results.md / crossreg.png (EF20).

    python3 simulation/flyback/eel19_report.py
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import flyback_sim as fs  # noqa: E402
import om_model as m  # noqa: E402
import options as opts  # noqa: E402
import report as rp  # noqa: E402
import run_flyback as rf  # noqa: E402

OUT = os.path.join(HERE, "out")
REF = "margin_sandwich_8_pre"
RAILS = list(fs.RAILS)
STD = [c["name"] for c in rf.cases()]
FULL = [c["name"] for c in rf.FULL_CASES]


def load(name):
    om = json.load(open(os.path.join(OUT, "om", f"{name}.json")))
    res = {}
    for c in rf.all_cases():
        p = os.path.join(OUT, "results", f"{name}__{c['name']}.json")
        if os.path.exists(p):
            res[c["name"]] = json.load(open(p))
    return om, res


def rng(res, rail, cases):
    v = [res[c][rail] for c in cases if c in res and res[c].get(rail) is not None]
    return (min(v), max(v)) if v else (None, None)


def main(names=None):
    names = names or [n for n in opts.EEL19_OPTIONS + opts.EEL19_TIW_OPTIONS
                      if os.path.exists(os.path.join(OUT, "om", f"{n}.json"))]
    allx = [REF] + names
    data = {n: load(n) for n in allx}
    s = ["# EEL19 options – summary tables", "",
         "Generated by `python3 simulation/flyback/eel19_report.py` from the cached run_flyback.py results "
         "(OpenMagnetics 1.7.41 inductance matrix, calibrated ngspice model). Reference: the EF20 recommendation "
         f"`{REF}`. Voltages are magnitudes. The standard range covers the same 15 load cases at 400 V as results.md "
         "(nom, min_*, max_*, light, idle); full10 / full15 / full15_325 are listed separately.", "",
         "## Magnetics", "",
         "Leakage = short-circuit inductance between effective windings, referred to the full primary "
         "(104 T for EEL19, 52 T for EF20) and, in brackets, scaled to 52 T (÷ 4) for a like-for-like comparison.", "",
         "| option | gap mm (MKF energy fit) | Lp µH | P–A5 | P–S15 | P–S5 | P–SHV | A5–S15 | A5–S5 | A5–SHV | build mm (window) |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for n in allx:
        om, _ = data[n]
        lk = rp.leakage_table(om) * 1e6
        Le, _Ne = rp.effective(om)
        sc = 4.0 if om["turns"][0] + (om["turns"][-1] if om["names"][-1] == "P2" else 0) > 60 else 1.0
        E = rp.EFFECTIVE

        def cell(i, j):
            v = lk[i][E.index(j)]
            return f"{v:.1f}" + (f" ({v / sc:.1f})" if sc > 1 else "")
        s.append(f"| {n} | {om['gap'] * 1e3:.3f} | {Le[0][0] * 1e6:.0f} | " +
                 " | ".join(cell(0, j) for j in ("A5", "S15", "S5", "SHV")) + " | " +
                 " | ".join(cell(2, j) for j in ("S15", "S5", "SHV")) +
                 f" | {om['geometry']['radial_build_mm']:.2f} ({om['geometry']['window_radial_mm']:.2f}) |")
    s += ["", "DC resistance at 60 °C (Ω): " + "; ".join(
        f"{n}: " + ", ".join(f"{a} {r:.3f}" for a, r in zip(data[n][0]["names"], data[n][0]["Rdc"])) for n in allx), ""]
    s += ["## Rails over the standard load cases at 400 V: nominal (min–max)", "",
          "| option | " + " | ".join(rp.dn(x) for x in RAILS) + " | 15V idle | Vcol max |", "|---" * (len(RAILS) + 3) + "|"]
    for n in allx:
        res = data[n][1]
        if "nom" not in res:
            continue
        std = [c for c in STD if c != "nom325"]
        cells = []
        for x in RAILS:
            lo, hi = rng(res, x, std)
            cells.append(f"{res['nom'][x]:.2f} ({lo:.2f}–{hi:.2f})")
        idle = f"{res['idle']['20V']:.2f}" if "idle" in res else "–"
        s.append(f"| {n} | " + " | ".join(cells) + f" | {idle} | {max(res[c]['vcol'] for c in std if c in res):.0f} |")
    s += ["", "## Spread (max − min over the standard cases at 400 V), V", "",
          "| option | " + " | ".join(rp.dn(x) for x in RAILS) + " |", "|---" * (len(RAILS) + 1) + "|"]
    for n in allx:
        res = data[n][1]
        if "nom" not in res:
            continue
        std = [c for c in STD if c != "nom325"]
        s.append(f"| {n} | " + " | ".join(f"{rng(res, x, std)[1] - rng(res, x, std)[0]:.2f}" for x in RAILS) + " |")
    s += ["", "## Full load (EEL19 only) and nom325", "",
          "| option | case | " + " | ".join(rp.dn(x) for x in RAILS) + " | Pin W | Ipk A | f kHz | u | Vcol pk V | D8 V_R | R45 W |",
          "|---|---|" + "---|" * (len(RAILS) + 6)]
    for n in allx:
        res = data[n][1]
        for c in ["nom325"] + FULL:
            r = res.get(c)
            if not r:
                continue
            s.append(f"| {n} | {c} | " + " | ".join(f"{r[x]:.2f}" for x in RAILS) +
                     f" | {r['pin']:.2f} | {r['ipk']:.3f} | {r['fsw'] / 1e3:.1f} | {r['u']:.3f} | {r['vcol']:.0f} | "
                     f"{r['-100V BIAS vrev']:.0f} | {r['pr45']:.3f} |")
    s += ["", "## Rectifier peak reverse voltage, max over all cases at 400 V (V, 50 ns filtered)", "",
          "| option | D5 (15V) | D6 (5V) | D4 (15V_ISO_SEC) | D29 (5V_ISOL) | D14 (-5V_SEC) | D8 (-80 V) |",
          "|---|---|---|---|---|---|---|"]
    for n in allx:
        res = data[n][1]
        cs = [c for c in res if c not in ("nom325", "full15_325")]
        if not cs:
            continue
        s.append(f"| {n} | " + " | ".join(f"{max(res[c][x + ' vrev'] for c in cs):.0f}" for x in RAILS) + " |")
    lo_rows = []
    # eel19_recommended (= eel19_sandwich_b_pre3 with the spacer gap) is run for nom / full15
    # only, as the loss reference of the TIW variants (same gap type)
    for n in allx + [x for x in ("eel19_recommended",) if x not in allx]:
        for case in ("nom", "full15"):
            p = os.path.join(OUT, "losses", f"{n}.json" if case == "nom" else f"{n}__{case}.json")
            if os.path.exists(p):
                lo = json.load(open(p))
                per = lo.get("per_winding_W") or {}
                lo_rows.append(f"| {n} | {case} | {lo.get('winding_losses_W', float('nan')):.3f} | "
                               f"{sum(v for k, v in per.items() if k in ('P', 'P1', 'P2')):.3f} | "
                               f"{lo.get('core_losses_W_ROSHEN', float('nan')):.3f} / {lo.get('core_losses_W_STEINMETZ', float('nan')):.3f} / "
                               f"{lo.get('core_losses_W_IGSE', float('nan')):.3f} | {lo.get('B_peak_T', float('nan')):.3f} |")
    if lo_rows:
        s += ["", "## Losses (MKF, 60 °C windings; core N87 for EF20, PC40 for EEL19)", "",
              "| option | case | winding W | of which primary W | core W Roshen / Steinmetz / iGSE | Bpk T |",
              "|---|---|---|---|---|---|"] + lo_rows
    with open(os.path.join(HERE, "eel19_results.md"), "w") as f:
        f.write("\n".join(s) + "\n")
    for n in names:
        if n in ("eel19_spacer_pre", "eel19_sandwich_pre3", "eel19_sandwich_b_pre3"):
            continue                      # same winding as an option without the suffix
        opt = opts.get(n)
        m.use_core(opt.get("core"))
        rp.geometry_png(n, os.path.join(HERE, f"geometry_{n.replace('_pre3', '').replace('_pre', '')}.png"))
    print("\n".join(s))


if __name__ == "__main__":
    main(sys.argv[1:] or None)
